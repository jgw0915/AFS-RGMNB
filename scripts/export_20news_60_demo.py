"""Export 60 genuine sklearn 20 Newsgroups posts and AFS-RGMNB word counts.

Run from repository root:
  python scripts/export_20news_60_demo.py --selection first60 \
      --output outputs/2026-11-23/20news_demo

The first CSV preserves the downloaded text (headers/quotes included by default).
The second is generated by the project's DocumentPreprocessing/CountVectorizer.
Not the senior archive and not a held-out or final thesis experiment.
Do not commit original posts, identifiers or per-document output to public Git.
"""
from __future__ import annotations

import argparse
from collections import Counter
import csv
import hashlib
import json
from pathlib import Path

import numpy as np
from sklearn import __version__ as sklearn_version
from sklearn.datasets import fetch_20newsgroups
from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS

from afs_rgmnb.features.document import DocumentPreprocessing, document_vectorizer

SEED = 42


def select_indices(target, mode: str) -> list[int]:
    labels = np.asarray(target)
    if len(labels) < 60:
        raise ValueError("At least 60 source documents are required")
    if mode == "first60":
        return list(range(60))
    if mode != "three_per_class":
        raise ValueError("Unknown selection method")
    classes = sorted({int(value) for value in labels})
    if len(classes) != 20:
        raise ValueError("Three-per-class demo expects exactly 20 classes")
    picked, counts = [], Counter()
    for index, label in enumerate(labels):
        key = int(label)
        if counts[key] < 3:
            picked.append(index)
            counts[key] += 1
        if len(picked) == 60:
            break
    if len(picked) != 60 or len(counts) != 20:
        raise ValueError("Could not select 3 documents from each of 20 classes")
    return picked


def _safe_output(output: Path) -> Path:
    output = output.resolve()
    repo_root = Path(__file__).resolve().parents[1]
    if output.is_relative_to(repo_root) and not output.is_relative_to(repo_root / "outputs"):
        raise ValueError("Within this public Git repo, the demo output must be under ignored outputs/")
    return output


def export_demo(*, output: Path, selection: str = "first60",
                strip_metadata: bool = False, data_home: Path | None = None) -> dict:
    output = _safe_output(Path(output))
    # With remove=(), sklearn returns the original downloaded message body, not
    # already-vectorized counts. Header handling in the project's analyzer below
    # is explicit and independent of the original CSV.
    removed = ("headers", "footers", "quotes") if strip_metadata else ()
    kwargs = {"subset": "all", "shuffle": True, "random_state": SEED, "remove": removed}
    if data_home is not None:
        kwargs["data_home"] = str(data_home)
    dataset = fetch_20newsgroups(**kwargs)
    selected = select_indices(dataset.target, selection)
    texts = [dataset.data[i] for i in selected]
    y = [int(dataset.target[i]) for i in selected]
    names = [dataset.target_names[label] for label in y]
    ids = [f"sklearn20ng_{index:05d}" for index in selected]

    # The historical senior stoplist and raw corpus are unavailable. The
    # sklearn English stoplist is a declared demonstration alternative.
    policy = DocumentPreprocessing(
        lowercase=True,
        stopwords=tuple(sorted(ENGLISH_STOP_WORDS)),
        stopword_source="sklearn ENGLISH_STOP_WORDS (demo, not senior stoplist)",
        porter_mode="original",
        remove_headers=not strip_metadata,
    )
    vectorizer = document_vectorizer(policy)
    X = vectorizer.fit_transform(texts).tocsr()
    vocabulary = vectorizer.get_feature_names_out()
    if X.shape[0] != 60 or X.shape[1] == 0 or (X.data < 0).any():
        raise ValueError("Unexpected extraction dimensions/count values")
    if np.any(X.data != np.floor(X.data)):
        raise ValueError("Feature values must be integer occurrence counts")

    # Write only after extraction succeeded. Do not stage these data artifacts.
    output.mkdir(parents=True, exist_ok=True)
    originals = output / "20news_original_60.csv"
    with originals.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(("sample_id", "source_index", "class_id", "class_name",
                         "raw_text_sha256", "document_text"))
        for sample_id, source_index, cls, name, text in zip(ids, selected, y, names, texts):
            writer.writerow((sample_id, source_index, cls, name,
                             hashlib.sha256(text.encode("utf-8")).hexdigest(), text))

    counts_csv = output / "20news_extracted_word_counts_60.csv"
    with counts_csv.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(("sample_id", "source_index", "class_id", "class_name",
                         "feature_index", "term", "occurrence_count"))
        for row in range(X.shape[0]):
            start, stop = X.indptr[row:row + 2]
            # Column indexes refer to THIS demo's fitted vocabulary only.
            for col, count in sorted(zip(X.indices[start:stop], X.data[start:stop])):
                writer.writerow((ids[row], selected[row], y[row], names[row],
                                 int(col), vocabulary[int(col)], int(count)))

    manifest = {
        "schema_version": 1,
        "purpose": "60-document raw text to integer word counts teaching/demo only",
        "source_api": "sklearn.datasets.fetch_20newsgroups",
        "dataset_subset": "all",
        "source_total_documents": len(dataset.data),
        "selection": selection,
        "random_state": SEED,
        "shuffle": True,
        "download_remove": list(removed),
        "original_csv_is_unmodified_downloaded_text": not strip_metadata,
        "project_analyzer_remove_headers": policy.remove_headers,
        "stopword_source": policy.stopword_source,
        "porter_mode": policy.porter_mode,
        "lowercase": policy.lowercase,
        "sample_count": len(selected),
        "source_indices": selected,
        "class_distribution": dict(sorted(Counter(names).items())),
        "observed_vocabulary_features": int(X.shape[1]),
        "nonzero_word_count_entries": int(X.nnz),
        "sum_occurrence_counts": int(X.sum()),
        "feature_values": "nonnegative integer occurrence counts, not TF-IDF",
        "feature_index_scope": "0-based local 60-document fitted vocabulary",
        "vocabulary_fit_scope": "all 60 demonstration documents, not a train/test protocol",
        "project_component": "afs_rgmnb.features.document.document_vectorizer",
        "scikit_learn_version": sklearn_version,
        "historical_senior_dataset_equivalent": False,
        "caveats": [
            "sklearn's original 20 Newsgroups and the senior 18,828-row archive are different versions",
            "only 60 sampled documents: does not establish thesis n>=500 screening eligibility",
            "raw downloaded messages may contain personal identifiers; output remains Git-ignored",
            "stopwords/tokenizer/stemmer are explicit alternatives, not verified senior reproduction",
            "the data and vocabulary cannot be used as a fitted test fold or accuracy result"
        ],
    }
    (output / "demo_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("outputs/2026-11-23/20news_demo"))
    parser.add_argument("--selection", choices=("first60", "three_per_class"), default="first60")
    parser.add_argument("--strip-metadata", action="store_true",
                        help="Also remove headers, footers and quotes from downloaded posts; not raw originals")
    parser.add_argument("--data-home", type=Path, help="Optional sklearn dataset cache directory")
    args = parser.parse_args()
    result = export_demo(output=args.output, selection=args.selection,
                         strip_metadata=args.strip_metadata, data_home=args.data_home)
    print(json.dumps({
        "output": str(Path(args.output).resolve()),
        "samples": result["sample_count"],
        "represented_classes": len(result["class_distribution"]),
        "observed_features": result["observed_vocabulary_features"],
        "nonzero_entries": result["nonzero_word_count_entries"],
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
